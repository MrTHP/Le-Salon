pub fn filtered(query: &str, french: bool) -> Vec<(&'static str, &'static str, &'static str)> {
    let needle = query.trim().to_lowercase();
    let mut out = Vec::new();
    for group in GROUPS {
        for item in group.items {
            let name = if french { item.1 } else { item.2 };
            if needle.is_empty()
                || item.0.contains(&needle)
                || name.to_lowercase().contains(&needle)
                || item.2.to_lowercase().contains(&needle)
            {
                out.push(*item);
            }
        }
    }
    out
}
